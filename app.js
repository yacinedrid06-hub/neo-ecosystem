function getApiErrorMessage(message) {
  const key = apiErrors.get(message);
  if (key) return text(key);
  return state.language === "en" && message ? message : text("genericError");
}

async function api(url, options = {}) {
  const headers = new Headers(options.headers || {});
  if (options.body && !headers.has("content-type")) headers.set("content-type", "application/json");
  const response = await fetch(url, { ...options, headers, credentials: "same-origin" });
  if (response.status === 204) return null;
  const payload = await response.json();
  if (!response.ok) {
    const error = new Error(payload.error || text("genericError"));
    error.status = response.status;
    if (response.status === 401 && state.user) {
      showAuth();
      setStatus("auth-error", text("signInAgain"), true);
    }
    throw error;
  }
  return payload;
}

