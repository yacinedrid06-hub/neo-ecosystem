function getLocalDateKey() {
  const now = new Date();
  return `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, "0")}-${String(now.getDate()).padStart(2, "0")}`;
}

function isValidDate(value) {
  if (typeof value !== "string" || !/^\d{4}-\d{2}-\d{2}$/.test(value)) return false;
  const date = new Date(`${value}T00:00:00.000Z`);
  return Number.isFinite(date.getTime()) && date.toISOString().slice(0, 10) === value;
}

function formatDate(value) {
  const date = new Date(`${value}T00:00:00`);
  return new Intl.DateTimeFormat(state.language, { day: "numeric", month: "short", year: "numeric" }).format(date);
}

function renderDate() {
  const now = new Date();
  document.getElementById("day-number").textContent = new Intl.DateTimeFormat(state.language, { day: "2-digit" }).format(now);
  document.getElementById("date-label").textContent = new Intl.DateTimeFormat(state.language, { month: "long", year: "numeric" }).format(now);
  document.getElementById("year").textContent = now.getFullYear();
}

