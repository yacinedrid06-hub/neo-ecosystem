async function initialize() {
  try {
    const storedLanguage = safeLocalStorageGet("neo-language");
    if (storedLanguage === "ar" || storedLanguage === "en") state.language = storedLanguage;
  } catch (error) {
    console.error("Could not load language preference", error);
  }
  setLanguage(state.language);
  try {
    const result = await api("/api/auth/me");
    await openWorkspace(result.user);
  } catch (error) {
    showAuth();
    if (error.status !== 401) {
      console.error("Could not check the current session", error);
      document.getElementById("auth-error").textContent = getApiErrorMessage(error.message);
    }
  }
  if ("serviceWorker" in navigator) {
    navigator.serviceWorker.register("/sw.js").catch((error) => {
      console.error("Could not register the offline app shell", error);
    });
  }
}

