function renderProjects(target, projects, compact = false) {
  target.replaceChildren();
  for (const project of projects) {
    const card = document.createElement("article");
    card.className = compact ? "project-card project-card-compact" : "project-card";
    const details = document.createElement("div");
    details.className = "project-card-details";
    details.append(createTextElement("h3", "project-card-title", project.title));
    if (project.description) details.append(createTextElement("p", "project-card-description", project.description));
    const actions = document.createElement("div");
    actions.className = "project-card-actions";
    if (compact) {
      actions.append(createTextElement("span", "project-status-label", text(project.status === "planned" ? "statusPlanned" : project.status === "active" ? "statusActive" : "statusDone")));
    } else {
      const status = document.createElement("select");
      status.className = "project-status-select";
      status.setAttribute("aria-label", `${project.title}: ${text("projectStatusLabel")}`);
      for (const value of ["planned", "active", "done"]) {
        const option = document.createElement("option");
        option.value = value;
        option.textContent = text(value === "planned" ? "statusPlanned" : value === "active" ? "statusActive" : "statusDone");
        option.selected = project.status === value;
        status.append(option);
      }
      status.dataset.projectStatus = project.id;
      actions.append(status);
    }
    if (!compact) {
      const edit = document.createElement("button");
      edit.type = "button";
      edit.className = "edit-project";
      edit.dataset.editProject = project.id;
      edit.textContent = text("editProject");
      edit.setAttribute("aria-label", `${text("editProject")}: ${project.title}`);
      actions.append(edit);
      const remove = document.createElement("button");
      remove.type = "button";
      remove.className = "delete-project";
      remove.dataset.deleteProject = project.id;
      remove.textContent = text("deleteProject");
      remove.setAttribute("aria-label", `${text("deleteProject")}: ${project.title}`);
      actions.append(remove);
    }
    card.append(details, actions);
    target.append(card);
  }
}

